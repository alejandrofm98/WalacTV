    val items: List<CatalogItemDto> = emptyList(),
    val total: Int = 0,
    val page: Int = 1,
    @SerializedName("page_size") val pageSize: Int = 24,
    val pages: Int = 0,
    @SerializedName("has_next") val hasNext: Boolean = false,
